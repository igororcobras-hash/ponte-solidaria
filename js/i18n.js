  const UI_OF = { 'pt-BR': 'pt', 'pt-PT': 'pt', es: 'es', en: 'en', fr: 'fr' };

  let current = 'pt-BR';

  function uiLang(code) { return UI_OF[code] || 'en'; }

  window.I18N = {
    LANGS,
    has: (code) => !!LANGS.find((l) => l[0] === code),
    isFull: (code) => !!UI_OF[code],
    get: () => current,
    set(code, persist) {
      current = code;
      if (persist) { try { localStorage.setItem('ps_lang', code); } catch (e) {} }
      const info = LANGS.find((l) => l[0] === code);
      document.documentElement.lang = code;
      document.documentElement.dir = (info && info[4]) || 'ltr';
    },
    saved() { try { return localStorage.getItem('ps_lang'); } catch (e) { return null; } },
    guess() {
      const nav = (navigator.languages || [navigator.language || 'pt-BR']);
      for (const n of nav) {
        const exact = LANGS.find((l) => l[0].toLowerCase() === String(n).toLowerCase());
        if (exact) return exact[0];
        const base = String(n).split('-')[0].toLowerCase();
        if (base === 'pt') return 'pt-BR';
        if (base === 'zh') return 'zh-CN';
        if (base === 'no' || base === 'nn') return 'nb';
        const b = LANGS.find((l) => l[0].split('-')[0].toLowerCase() === base);
        if (b) return b[0];
      }
      return 'pt-BR';
    },
    t(key, vars) {
      const pack = STR[uiLang(current)] || STR.en;
      let s = pack[key];
      if (s === undefined) s = STR.en[key];
      if (s === undefined) s = STR.pt[key];
      if (s === undefined) return key;
      if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
      return s;
    },
    speechLang() { return uiLang(current) === 'pt' ? (current === 'pt-PT' ? 'pt-PT' : 'pt-BR') : (UI_OF[current] ? current : 'en'); },
    money(v) {
      try { return new Intl.NumberFormat(current, { style: 'currency', currency: 'BRL', maximumFractionDigits: 0 }).format(Number(v || 0)); }
      catch (e) { return 'R$ ' + Number(v || 0).toFixed(0); }
    },
    date(ts) {
      try { return new Intl.DateTimeFormat(current, { day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(ts)); }
      catch (e) { return new Date(ts).toLocaleDateString(); }
    }
  };
